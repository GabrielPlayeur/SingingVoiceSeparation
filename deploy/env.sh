#!/usr/bin/env bash
# SINGLE deployment configuration. Sourced by all deploy/*.sh, also read by the Python scripts (deploy/_env.py).
#
# - Every value that depends on AutoDL is marked "TODO: check in the AutoDL docs": it is only written here.
# - The values specific to THIS rental (SSH_HOST, SSH_PORT...) go in deploy/env.local.sh (ignored by git, so that
#   the tree stays clean: the experiment queue refuses to start otherwise).
# - Secrets (GITHUB_TOKEN, WANDB_API_KEY) NEVER go in a file: environment variables only.
# - Any variable can be overridden by the environment (e.g. DATA_ROOT=/tmp/x deploy/...).

_ENV_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=/dev/null
if [ -f "$_ENV_DIR/env.local.sh" ]; then source "$_ENV_DIR/env.local.sh"; fi

# ---- SSH connection (local side): to be filled in env.local.sh with the values of the AutoDL panel ---------------------
: "${SSH_HOST:=}"                 # e.g. connect.xxx.seetacloud.com
: "${SSH_PORT:=22}"
: "${SSH_USER:=root}"
: "${SSH_KEY:=}"                  # path of the private key; empty = default key / password

# ---- Repository -------------------------------------------------------------------------------------------------------
: "${REPO_URL:=https://github.com/GabrielPlayeur/SingingVoiceSeparation.git}"   # or a .bundle file (git bundle) as a fallback
: "${GIT_TAG:=lr-v1}"             # tag to deploy by default (setup_server.sh and run_queue.py --tag)

# ---- Disks and folders (server side) -----------------------------------------------------------------------------------
: "${DATA_ROOT:=/root/autodl-tmp}"   # TODO: check in the AutoDL docs (data disk, and its size: >= 60 GB needed)
: "${SERVER_REPO:=$HOME/SingingVoiceSeparation}"           # clone + .venv (~7 GB): SYSTEM disk (30 GB), to keep the 50 GB of data disk for MUSDB18 (~41 GB)
: "${BOOTSTRAP_DIR:=/root/svs_bootstrap}"                  # where push_bootstrap.sh copies deploy/ before the first clone
: "${MUSDB_RAW:=$DATA_ROOT/musdb18}"                       # {train,test}/*.stem.mp4
: "${MUSDB_PROCESSED:=$MUSDB_RAW/processed}"               # wavs generated by src/data/preprocessing.py (~35 GB)
: "${SPLIT_PATH:=$MUSDB_RAW/split.json}"
: "${ORACLE_CACHE_DIR:=$DATA_ROOT/oracle_cache}"
: "${RUNS_DIR:=$DATA_ROOT/runs}"                           # runs/<tag>/<name>_s<seed>/
: "${DOWNLOAD_DIR:=$DATA_ROOT/downloads}"

# ---- Data (local side) -------------------------------------------------------------------------------------------------
: "${LOCAL_MUSDB:=}"              # empty = <repo>/musdb18
# KEEP_ZIP=1 to keep the zip (4.7 GB) after extraction; deleted by default (50 GB data disk)
: "${DATASET_URL:=https://zenodo.org/records/1117372/files/musdb18.zip}"   # TODO: check the URL (compressed MUSDB18, ~4.7 GB)
: "${HF_REPO:=}"                    # data relay: user/name of a PRIVATE Hugging Face dataset repository (hf_upload.sh / get_data_hf.sh)
: "${HF_CKPT_REPO:=}"               # checkpoint relay: PRIVATE Hugging Face model repository (push_ckpt_hf.sh / get_ckpt_hf.sh); empty = <user of HF_REPO>/svs-checkpoints
: "${LOCAL_RESULTS_DIR:=}"        # empty = <repo>/outputs/server

# ---- AutoDL-specific: to check in the AutoDL docs before buying ------------------------------------------------------
: "${NET_TURBO_FILE:=/etc/network_turbo}"   # TODO: check in the AutoDL docs (GitHub network accelerator: file to "source"). Empty = none
: "${SHUTDOWN_CMD:=shutdown}"               # TODO: check in the AutoDL docs (shutdown from the terminal); check that billing stops
: "${CPU_CORES:=}"                          # TODO: check in the AutoDL docs (cores really allocated; os.cpu_count() may see the host's). Empty = nproc
# TODO: check in the AutoDL docs: slow sources from China? If so, uncomment/adapt (variables read by uv):
# export UV_DEFAULT_INDEX="https://pypi.tuna.tsinghua.edu.cn/simple"      # PyPI mirror (pyproject.toml also points to download.pytorch.org)
# export UV_PYTHON_INSTALL_MIRROR="..."                                   # Python mirror (otherwise uv downloads from GitHub)
# export UV_PYTHON="/usr/bin/python3.12"                                  # or use the image's Python 3.12
# Installation through a mirror (China): if PYPI_MIRROR is non-empty, setup_server.sh does not use `uv sync --frozen` (which downloads
# the URLs pinned in uv.lock, from pythonhosted.org / pytorch.org: ~0.7 to 1.3 MB/s measured from AutoDL) but `uv export` +
# `uv pip install`: the SAME exact versions as the lock, from the mirror (~7.6 MB/s measured). Values measured/checked on 2026-10-14.
# Outside China: PYPI_MIRROR= (empty) to go back to `uv sync --frozen`.
: "${PYPI_MIRROR=https://mirrors.aliyun.com/pypi/simple/}"                 # TODO: check in the AutoDL docs (it is also the mirror of the image's pip.conf)
: "${TORCH_WHEELS_URL=https://mirrors.aliyun.com/pytorch-wheels/cu128/}"   # folder of the torch/torchvision +cu128 wheels (files are reachable, not their listing); empty or failing: fall back to TORCH_INDEX
: "${TORCH_INDEX:=https://download.pytorch.org/whl/cu128}"
: "${UV_INSTALL_CMD:=python3 -m pip install uv}"   # TODO: check in the AutoDL docs (pip or access to astral.sh?)

# ---- Execution ---------------------------------------------------------------------------------------------------------
: "${DEFAULT_PARALLEL:=3}"        # number of simultaneous runs (training + evaluation); to be set with benchmark_parallel.sh
: "${WANDB_MODE:=offline}"        # offline | online (online needs WANDB_API_KEY in the environment)
: "${SHUTDOWN_WAIT_MIN:=180}"     # run_queue.py --shutdown: max wait for the FETCHED file before giving up the shutdown

export HF_REPO HF_CKPT_REPO SSH_HOST SSH_PORT SSH_USER SSH_KEY REPO_URL GIT_TAG DATA_ROOT SERVER_REPO BOOTSTRAP_DIR MUSDB_RAW MUSDB_PROCESSED SPLIT_PATH \
       ORACLE_CACHE_DIR RUNS_DIR DOWNLOAD_DIR LOCAL_MUSDB DATASET_URL LOCAL_RESULTS_DIR NET_TURBO_FILE SHUTDOWN_CMD CPU_CORES \
       UV_INSTALL_CMD PYPI_MIRROR TORCH_INDEX TORCH_WHEELS_URL DEFAULT_PARALLEL WANDB_MODE SHUTDOWN_WAIT_MIN
